import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sksurv.datasets import load_gbsg2
from lifelines import CoxPHFitter

# Set seed for reproducibility
np.random.seed(42)
plt.style.use('seaborn-v0_8-whitegrid')

# Load dataset
X, y = load_gbsg2()
df = X.copy()
df['event'] = y['cens'].astype(int)
df['time'] = y['time']

# Clean categorical features into numerical representations
df['horTh'] = (df['horTh'] == 'yes').astype(int)
df['menostat'] = (df['menostat'] == 'Post').astype(int)

# Map tumor grade (tgrade) to ordinal scale: I -> 1, II -> 2, III -> 3
grade_map = {'I': 1.0, 'II': 2.0, 'III': 3.0}
df['tgrade_true'] = df['tgrade'].map(grade_map).astype(float)
df = df.drop(columns=['tgrade'])

print(f"Dataset loaded: {df.shape[0]} patients, {df['event'].sum()} observed events.")
df.head()

# Simulate upstream NLP extraction output for tumor size (tsize)
# Assume the NLP model extracts a point estimate plus a patient-specific uncertainty (std dev)
# Some reports are ambiguous (high uncertainty), others are clear (low uncertainty)
df['tsize_uncertainty_sd'] = np.random.uniform(2.0, 12.0, size=len(df))

# Observed (noisy) extraction point estimate
df['tsize_extracted'] = np.maximum(
    1.0, df['tsize'] + np.random.normal(0, df['tsize_uncertainty_sd'])
)

# Visualize upstream extraction uncertainty for the first 15 patients
plt.figure(figsize=(10, 4))
subset = df.iloc[:15]
plt.errorbar(
    range(15), subset['tsize_extracted'], yerr=1.96 * subset['tsize_uncertainty_sd'],
    fmt='o', color='#1f77b4', ecolor='#aec7e8', elinewidth=3, capsize=4, label='Extracted Size (±95% CI)'
)
plt.scatter(range(15), subset['tsize'], color='#d62728', zorder=5, label='True Clinical Size')
plt.xticks(range(15), [f"Pt {i}" for i in range(15)])
plt.ylabel("Tumor Size (mm)")
plt.title("Simulated NLP Extraction Uncertainty from Pathology Reports")
plt.legend()
plt.tight_layout()
plt.show()

features = ['age', 'menostat', 'horTh', 'pnodes', 'progrec', 'estrec', 'tgrade_true']

# 1. Naive Model (ignores extraction uncertainty)
df_naive = df[features + ['tsize_extracted', 'time', 'event']].copy()
cph_naive = CoxPHFitter()
cph_naive.fit(df_naive, duration_col='time', event_col='event')

# 2. Uncertainty-Propagating Monte Carlo Ensemble (M = 100 realizations)
M = 100
time_grid = np.linspace(1, 2500, 200)

# Select a specific high-uncertainty patient to analyze downstream impact
high_unc_idx = df['tsize_uncertainty_sd'].idxmax()
patient_row = df.loc[[high_unc_idx]].copy()

survival_curves_mc = []
hazard_ratios_tsize = []

for m in range(M):
    # Step A: Sample from the upstream NLP extraction distribution for training & inference
    df_mc = df[features + ['time', 'event']].copy()
    df_mc['tsize_sampled'] = np.maximum(
        1.0, np.random.normal(df['tsize_extracted'], df['tsize_uncertainty_sd'])
    )

    # Step B: Fit time-to-event model on realized dataset
    cph_mc = CoxPHFitter()
    cph_mc.fit(df_mc, duration_col='time', event_col='event')
    hazard_ratios_tsize.append(np.exp(cph_mc.params_['tsize_sampled']))

    # Step C: Sample patient's specific covariate value & predict survival curve
    pt_mc = patient_row[features].copy()
    pt_mc['tsize_sampled'] = max(
        1.0, np.random.normal(patient_row['tsize_extracted'].values[0],
                              patient_row['tsize_uncertainty_sd'].values[0])
    )
    surv_func = cph_mc.predict_survival_function(pt_mc, times=time_grid)
    survival_curves_mc.append(surv_func.values.flatten())

survival_curves_mc = np.array(survival_curves_mc)

# Compute mean and 95% credible intervals across Monte Carlo realizations
mean_surv = np.mean(survival_curves_mc, axis=0)
lower_ci = np.percentile(survival_curves_mc, 2.5, axis=0)
upper_ci = np.percentile(survival_curves_mc, 97.5, axis=0)

# Naive point prediction for the same patient
naive_surv = cph_naive.predict_survival_function(
    df_naive.loc[[high_unc_idx]], times=time_grid
).values.flatten()

plt.figure(figsize=(9, 5))
plt.plot(time_grid, naive_surv, '--', color='#d62728', linewidth=2,
         label='Naive Cox PH (Ignores NLP Extraction Uncertainty)')
plt.plot(time_grid, mean_surv, color='#1f77b4', linewidth=2.5,
         label='Uncertainty-Propagated Mean Survival')
plt.fill_between(time_grid, lower_ci, upper_ci, color='#1f77b4', alpha=0.25,
                 label='95% Propagated Survival Interval (Upstream Uncertainty)')

plt.title(f"Downstream Survival Prediction for Patient #{high_unc_idx} (High Report Ambiguity)")
plt.xlabel("Time (Days)")
plt.ylabel("Recurrence-Free Survival Probability S(t)")
plt.ylim(0.2, 1.02)
plt.legend(loc='lower left')
plt.tight_layout()
plt.show()

# Print summary metrics for clinical decision support
idx_5yr = np.argmin(np.abs(time_grid - 1825))
print(f"5-Year Survival (Naive Point Estimate): {naive_surv[idx_5yr]:.1%}")
print(f"5-Year Survival (Propagated 95% Interval): {mean_surv[idx_5yr]:.1%} "
      f"[{lower_ci[idx_5yr]:.1%}, {upper_ci[idx_5yr]:.1%}]")

